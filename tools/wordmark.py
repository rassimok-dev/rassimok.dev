#!/usr/bin/env python3
"""Generate the start page (index.html): the word "rassimok" drawn as a
bundle of five parallel strands.

Each glyph is a single centre-line path. The strands come from stacking that
path five times with shrinking stroke widths, alternating ink and background,
so one path reads as five hairlines that bend, join and end together. Every
layer is written out in full rather than reused with <use>, because CSS
animations inside <use> shadow trees are not reliable in Safari.

    python3 tools/wordmark.py          # rewrite index.html
    python3 tools/wordmark.py --check  # CI: fail if index.html is stale

Edit the glyphs here, never index.html by hand.
"""
import pathlib
import sys

BUNDLE = 13.0                     # total width of the five strands
UNIT = BUNDLE / 9                 # five lines, four gaps, all equal
WIDTHS = [round(BUNDLE - 2 * i * UNIT, 3) for i in range(5)]
GAP = 11.0                        # space between glyph extents
TOP, BASE = 33.5, 106.5           # x-height edges of the bundle


def circle(cx, cy, r):
    return (f"M{cx - r:g} {cy:g}a{r:g} {r:g} 0 1 1 {2 * r:g} 0"
            f"a{r:g} {r:g} 0 1 1 {-2 * r:g} 0")


# Each glyph: (width, [centre-line paths]) in local coordinates, x from 0.
GLYPHS = {
    "r": (39.5, ["M6.5 106.5V33.5", "M6.5 70A30 30 0 0 1 36.5 40h3"]),
    "a": (73, [circle(36.5, 70, 30), "M66.5 33.5V106.5"]),
    "s": (49, ["M40.09 47.5A18 15 0 1 0 24.5 70A18 15 0 1 1 8.91 92.5"]),
    "i": (26, ["M13 106.5V33.5", circle(13, 12, 6.5)]),
    "m": (73, ["M6.5 106.5V55A15 15 0 0 1 36.5 55V106.5",
               "M36.5 55A15 15 0 0 1 66.5 55V106.5"]),
    "o": (73, [circle(36.5, 70, 30)]),
    "k": (50, ["M6.5 106.5V-1", "M42 40L6.5 74", "M21 60.1L44 106.5"]),
}
WORD = "rassimok"


def layout():
    x, out = 0.0, []
    for n, ch in enumerate(WORD, 1):
        w, paths = GLYPHS[ch]
        out.append((n, ch, x, paths))
        x += w + GAP
    return out, x - GAP


def node_centre(placed):
    for n, ch, x, _ in placed:
        if ch == "i":
            return x + 13, 12
    raise ValueError("no i in the word")


def svg():
    placed, width = layout()
    pad = 14
    vb = f"{-pad:g} {-14:g} {width + 2 * pad:g} {BASE + 14 + 14:g}"
    lines = [f'<svg class="word" viewBox="{vb}" aria-hidden="true" focusable="false">']
    for layer in range(5):
        lines.append(f'<g class="ink l{layer}">')
        for n, ch, x, paths in placed:
            for d in paths:
                lines.append(f'<path class="g{n}" transform="translate({x:g} 0)" d="{d}" pathLength="1"/>')
        lines.append("</g>")
    lines.append('<g class="pk">')
    for n, ch, x, paths in placed:
        for d in paths:
            lines.append(f'<path class="g{n}" transform="translate({x:g} 0)" d="{d}" pathLength="1"/>')
    lines.append("</g>")
    cx, cy = node_centre(placed)
    lines.append(f'<circle class="ping" cx="{cx:g}" cy="{cy:g}" r="{BUNDLE:g}"/>')
    lines.append("</svg>")
    return "\n".join(lines)


def page():
    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="color-scheme" content="dark">
<meta name="theme-color" content="#0a0b0d">
<title>rassimok</title>
<meta name="description" content="rassimok: software engineer. Backends, infrastructure, and the occasional thing that routes packets.">
<link rel="stylesheet" href="/style.css">
<link rel="icon" href="/favicon.svg" type="image/svg+xml">
</head>
<!-- Generated by tools/wordmark.py. Edit the generator, not this file. -->
<body class="splash">
<main>
<h1><a class="mark" href="/about/"><span class="sr">rassimok</span>
{svg()}
</a></h1>
</main>
</body>
</html>
"""


def main():
    target = pathlib.Path(__file__).resolve().parent.parent / "index.html"
    html = page()
    if "--check" in sys.argv:
        if target.read_text(encoding="utf-8") != html:
            sys.exit("index.html is out of date: run python3 tools/wordmark.py")
        print("OK: index.html matches tools/wordmark.py")
        return
    target.write_text(html, encoding="utf-8")
    print(f"wrote {target} ({len(html.encode())} bytes)")


if __name__ == "__main__":
    main()
